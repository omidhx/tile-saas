import { test } from "node:test";
import assert from "node:assert/strict";
import { normalize, matches } from "./search";

/**
 * جستجوی فارسی-آگاه. چیزهایی که خاموش می‌شکنند اگر نرمال‌سازی نباشد — و نماینده
 * فکر می‌کند «کالا نیست» در حالی که فقط جستجو کور بوده.
 */

test("ارقامِ فارسی و عربی به لاتین نرمال می‌شوند", () => {
  assert.equal(normalize("۶۰۶۰"), "6060");
  assert.equal(normalize("٦٠٦٠"), "6060", "ارقامِ عربی هم");
});

test("ي/ك عربی به ی/ک فارسی", () => {
  // کاراکترِ عربیِ ي (U+064A) و کافِ عربی ك (U+0643)
  assert.equal(normalize("كاشي"), "کاشی");
});

test("🔴 «۶۰۶۰» فارسی کدِ لاتینِ GB-6060 را پیدا می‌کند", () => {
  // خطِ اصلیِ فیچر: نماینده با کیبوردِ فارسی عدد تایپ می‌کند، کالا کدِ لاتین دارد
  assert.ok(matches("۶۰۶۰", ["گرانیت مشکی", "GB-6060", null, null]));
});

test("جستجو روی هر فیلد کار می‌کند و nullها را رد می‌کند", () => {
  assert.ok(matches("مشکی", ["گرانیت مشکی براق", "GB-6060", null, "S3"]), "نام");
  assert.ok(matches("s3", ["گرانیت", "GB-6060", null, "S3"]), "شید، بی‌حساسیت به بزرگی");
  assert.ok(!matches("قرمز", ["گرانیت مشکی", "GB-6060", null, null]), "چیزی که نیست");
});

test("جستجوی خالی یعنی همه", () => {
  assert.ok(matches("", ["هرچیزی"]));
  assert.ok(matches("   ", ["هرچیزی"]), "فقط فاصله هم خالی است");
});

test("کاربرِ عربی‌نویس هم کالای فارسی‌نوشته را پیدا می‌کند", () => {
  // نماینده «كاشي» (عربی) تایپ می‌کند، کالا «کاشی» (فارسی) ثبت شده
  assert.ok(matches("كاشي سفيد", ["کاشی سفید مات", "KS-3060", null, null]));
});
